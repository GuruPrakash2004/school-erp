-- School ERP schema (multi-tenant: every table except schools has school_id)
-- Tenant-safety pattern: every referenced table has UNIQUE (id, school_id), and every
-- child references (parent_id, school_id) so a row can never point at another school's data.

CREATE EXTENSION IF NOT EXISTS vector;  -- pgvector, not used by any table yet

CREATE TABLE schools (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE teachers (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    name      TEXT NOT NULL,
    email     TEXT NOT NULL,
    UNIQUE (school_id, email),
    UNIQUE (id, school_id)
);

CREATE TABLE classes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    name      TEXT NOT NULL,              -- e.g. '10-A'
    UNIQUE (school_id, name),
    UNIQUE (id, school_id)
);

CREATE TABLE subjects (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    name      TEXT NOT NULL,              -- e.g. 'Maths'
    UNIQUE (school_id, name),
    UNIQUE (id, school_id)
);

CREATE TABLE teaching_assignments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id  BIGINT NOT NULL REFERENCES schools(id),
    teacher_id BIGINT NOT NULL,
    class_id   BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    UNIQUE (teacher_id, class_id, subject_id),
    FOREIGN KEY (teacher_id, school_id) REFERENCES teachers (id, school_id),
    FOREIGN KEY (class_id,   school_id) REFERENCES classes  (id, school_id),
    FOREIGN KEY (subject_id, school_id) REFERENCES subjects (id, school_id)
);

CREATE TABLE students (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id   BIGINT NOT NULL REFERENCES schools(id),
    class_id    BIGINT NOT NULL,
    name        TEXT NOT NULL,
    roll_number INT NOT NULL,
    UNIQUE (class_id, roll_number),
    UNIQUE (id, school_id),
    FOREIGN KEY (class_id, school_id) REFERENCES classes (id, school_id)
);

CREATE TABLE parents (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id),
    name      TEXT NOT NULL,
    phone     TEXT NOT NULL,
    UNIQUE (id, school_id)
);

CREATE TABLE student_guardians (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id    BIGINT NOT NULL REFERENCES schools(id),
    student_id   BIGINT NOT NULL,
    parent_id    BIGINT NOT NULL,
    relationship TEXT NOT NULL,           -- e.g. 'mother', 'father'
    UNIQUE (student_id, parent_id),
    FOREIGN KEY (student_id, school_id) REFERENCES students (id, school_id),
    FOREIGN KEY (parent_id,  school_id) REFERENCES parents  (id, school_id)
);

CREATE TABLE marks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id  BIGINT NOT NULL REFERENCES schools(id),
    student_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    exam_name  TEXT NOT NULL,             -- e.g. 'Midterm'
    score      NUMERIC(5,2) NOT NULL CHECK (score >= 0 AND score <= 100),
    UNIQUE (student_id, subject_id, exam_name),
    FOREIGN KEY (student_id, school_id) REFERENCES students (id, school_id),
    FOREIGN KEY (subject_id, school_id) REFERENCES subjects (id, school_id)
);
